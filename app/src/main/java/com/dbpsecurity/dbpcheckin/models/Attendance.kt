package com.dbpsecurity.dbpcheckin.models

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

@Serializable
data class Attendance(
    val id: String? = null, // ID might be generated by DB
    @SerialName("created_at") val createdAt: String? = null,
    @SerialName("user_id") val userId: String,
    val status: String,
    @SerialName("check_in_time") val checkInTime: String? = null,
    @SerialName("check_out_time") val checkOutTime: String? = null,
    @SerialName("check_in_date") val checkInDate: String? = null,
    @SerialName("shift_name") val shiftName: String? = null,
    @SerialName("image_url") val imageUrl: String? = null,
    @SerialName("check_out_image") val checkOutImage: String? = null,
    @SerialName("location") val location: String? = null, // Renamed from latitude/longitude to match SQL text column if needed, but let's check SQL first. SQL uses 'location' text column.
    @SerialName("check_out_location") val checkOutLocation: String? = null
)

